export async function ensureTrainingPackSeed(pool, tenantId = 'default') {
  let upserted = 0;
  for (const art of BUILTIN_TRAINING_ARTICLES) {
    const existing = await pool.query(
      `SELECT id FROM knowledge_base WHERE title=$1 AND tenant_id=$2 LIMIT 1`,
      [art.title, tenantId]
    );
    const tags = art.tags || ['job_coach'];
    if (existing.rows?.[0]) {
      await pool.query(
        `UPDATE knowledge_base
            SET content=$2, category=$3, tags=$4, enabled=TRUE, updated_at=NOW(),
                training_module=COALESCE(training_module,'job_coach')
          WHERE id=$1`,
        [existing.rows[0].id, art.content, art.category, tags]
      );
    } else {
      await pool.query(
        `INSERT INTO knowledge_base
           (title, content, category, tags, scope, enabled, tenant_id, training_module)
         VALUES ($1,$2,$3,$4,'public',TRUE,$5,'job_coach')`,
        [art.title, art.content, art.category, tags, tenantId]
      );
    }
    upserted += 1;
  }
  return { ok: true, upserted };
}

export function getBuiltinArticleByTitle(title) {
  return BUILTIN_TRAINING_ARTICLES.find((a) => a.title === title) || null;
}

export function collectKeyPhrasesForHints(hints = []) {
  const phrases = new Set();
  for (const h of hints) {
    const art = BUILTIN_TRAINING_ARTICLES.find(
      (a) => a.title === h || a.title.includes(String(h).slice(0, 8))
    );
    if (art) art.key_phrases.forEach((p) => phrases.add(p));
  }
  // 也匹配「陪练内置」系列被 KB 标题替换后的核心包
  for (const art of BUILTIN_TRAINING_ARTICLES) {
    if (hints.some((h) => art.title.includes(String(h).slice(0, 6)) || String(h).includes(art.title.slice(0, 6)))) {
      art.key_phrases.forEach((p) => phrases.add(p));
    }
  }
  return [...phrases];
}

