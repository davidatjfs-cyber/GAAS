function card(p) {
  const pack = CATEGORY_PACK[p.category_key] || [];
  const hints = [...new Set([...(pack), ...(p.kb_title_hints || [])])];
  const base = {
    difficulty: 2,
    counterpart_role: 'customer',
    failure_signals: ['推诿', '争辩', '否认事实', '空话别着急'],
    sop_checklist: ['先致歉安抚', '确认事实', '给处理方案', '闭环告知'],
    experience_rubric: ['客人感到被重视', '语气稳定不顶撞', '方案具体可执行'],
    ...p,
    kb_title_hints: hints,
  };
  if (!base.model_answer) base.model_answer = defaultModelAnswer(base);
  if (!base.probe_questions?.length) base.probe_questions = defaultProbes(base);
  return base;
}

function defaultModelAnswer(c) {
  if (c.counterpart_role === 'hr') {
    return `标准答法：${c.success_criteria || '按员工手册执行'}。不确定就说去查手册/问主管，禁止编造制度或私自处理。`;
  }
  if (c.counterpart_role === 'regulator') {
    return `标准答法：${c.success_criteria || '配合检查、如实出示记录'}。问题项隔离停用并给整改时限，不说「大概」。`;
  }
  return `标准答法：先致歉安抚→确认事实（${(c.locked_facts || []).slice(0, 2).join('、')}）→给出方案与时间→闭环告知。成功标准：${c.success_criteria || ''}`;
}

function defaultProbes(c) {
  if (c.counterpart_role === 'hr') {
    return [
      '请用完整规定回答：可以做什么、不可以做什么？不要只回两个字。',
      '补充流程：第一时间找谁？要不要登记？',
      '情景题：同事私下让你通融，你怎么拒？',
    ];
  }
  if (c.counterpart_role === 'regulator') {
    return [
      '请出示或说明对应记录在哪里、谁负责。',
      '如果现场不符，你们的隔离和整改动作是什么？',
    ];
  }
  const f = (c.locked_facts || [])[0] || c.title;
  return [
    `就「${f}」给我明确处理方案。`,
    '时间和补偿说清楚：多久好？我能得到什么？',
    '处理好谁来跟我确认？',
  ];
}

